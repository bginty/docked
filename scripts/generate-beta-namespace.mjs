// Deterministic projection of reviewed SQL, never of live rows. Existing migrations
// remain authoritative and unchanged. Re-run --check in CI; future schema changes
// need an explicit beta migration rather than silently inheriting official DDL.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
const directory = "supabase/migrations/";
const output = directory + "20261008224142_beta_namespace_isolation.sql";
const sources = readdirSync(directory)
  .filter(
    (f) =>
      f.endsWith(".sql") &&
      f <= "20261008151700_fantasy_beta_result_isolation.sql",
  )
  .sort();
function project(sql) {
  return (
    sql
      .replace(
        /\b(public|private|fantasy)\./g,
        (_, schema) => `beta_${schema}.`,
      )
      .replace(
        /\bschema (?:if not exists )?(public|private|fantasy)(?=[;,\s])/g,
        (match) => match.replace(/(public|private|fantasy)$/, "beta_$1"),
      )
      .replace(/schema beta_public,private/g, "schema beta_public,beta_private")
      .replace(/search_path=private/g, "search_path=beta_private")
      .replace(/(schemaname=|nspname=)'(private|fantasy)'/g, "$1'beta_$2'")
      .replace(
        /has_schema_privilege\('docked_app','(public|private)'/g,
        "has_schema_privilege('docked_app','beta_$1'",
      )
      .replace(/\bdocked_app\b/g, "docked_beta_app")
      // Separate transaction lock domains. No beta wait may serialize official play.
      .replace(/71820341/g, "71820342")
  );
}
let result =
  "-- GENERATED by scripts/generate-beta-namespace.mjs. No live rows are copied.\n";
result +=
  "-- Additive schemas preserve every existing official object and record.\ncreate schema beta_public;\nrevoke all on schema beta_public from public,anon,authenticated;\n";
for (const file of sources) {
  const sql = readFileSync(directory + file, "utf8").replaceAll("\r\n", "\n");
  result += `\n-- SOURCE ${file} sha256=${createHash("sha256").update(sql).digest("hex")}\n${project(sql)}\n`;
}
result += `
-- Browsers cannot reach the beta schemas, even if someone exposes a schema in
-- PostgREST. Only the exact server role has the enumerated reviewed privileges.
revoke all on schema beta_public,beta_private,beta_fantasy from public,anon,authenticated,docked_app;
revoke all on all tables in schema beta_public,beta_private,beta_fantasy from public,anon,authenticated,docked_app;
revoke all on all functions in schema beta_public,beta_private,beta_fantasy from public,anon,authenticated,docked_app;
revoke all on all sequences in schema beta_public,beta_private,beta_fantasy from public,anon,authenticated,docked_app;
alter default privileges in schema beta_public,beta_private,beta_fantasy revoke execute on functions from public;
-- Keep dormant. Initialization and approved policy/admission are separate gates.
update beta_fantasy.settings set enabled=false;
-- A beta release can never be relabelled official. Existing beta history stays beta.
alter table beta_fantasy.production_releases add constraint beta_only check(channel='beta');
`;
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8").replaceAll("\r\n", "\n") !== result)
    throw Error("Beta namespace artifact differs from reviewed sources");
  console.log(
    "Beta namespace projection verified: " +
      sources.length +
      " unchanged source migrations",
  );
} else writeFileSync(output, result);
